export type DoctoralYear = "D1" | "D2" | "D3";
export type QuarterKey = "4〜6月" | "7〜9月" | "10〜12月" | "1〜3月";
export type QuarterDomain = "研究" | "キャリア" | "外部活動" | "生活";

export interface ScheduleItem {
  id: string;
  title: string;
  category: DoctoralScheduleCategory;
  progress: ScheduleProgressStatus;
  roadmapStatus: RoadmapStatus;
  evidence: ScheduleEvidenceKind;
  priority: Priority;
  detail?: string;
  nextAction?: string;
  candidates?: string[];
  conditions?: string[];
  sourceIds: string[];
}

export interface DoctoralMonthPlan {
  month: string;
  label: string;
  year: DoctoralYear;
  phaseLabel?: "M2" | DoctoralYear;
  focus: string;
  blockIds: string[];
  majorItems: ScheduleItem[];
  deadlines: ScheduleItem[];
  nextActions: string[];
  risks: string[];
  buffers: string[];
  decisions: string[];
  healthCheckId: "doctoral-monthly-health-baseline";
}

export interface DoctoralYearPlan {
  year: DoctoralYear;
  startMonth: string;
  endMonth: string;
  purpose: string;
  outcomes: string[];
  guardrail: string;
  status: RoadmapStatus;
  evidence: ScheduleEvidenceKind;
  sourceIds: string[];
}

export interface MajorScheduleBlock {
  id: string;
  title: string;
  year: DoctoralYear;
  category: DoctoralScheduleCategory;
  startMonth: string;
  endMonth: string;
  dateDisplay: string;
  duration: string;
  progress: ScheduleProgressStatus;
  roadmapStatus: RoadmapStatus;
  evidence: ScheduleEvidenceKind;
  priority: Priority;
  objective: string;
  candidates?: string[];
  deliverables: string[];
  prerequisites: string[];
  fallback: string;
  nextAction: string;
  sourceIds: string[];
}

export interface DoctoralQuarterPlan {
  id: string;
  year: DoctoralYear;
  quarter: QuarterKey;
  startMonth: string;
  endMonth: string;
  focus: string;
  domains: Record<QuarterDomain, string[]>;
  largeExternalActivityCount: number;
  buffer: string;
}

export interface DoctoralDecisionPoint {
  id: string;
  deadline: string;
  year: DoctoralYear;
  title: string;
  options: string[];
  criteria: string[];
  provisionalChoice: string;
  confirmations: string[];
  defaultAction: string;
  evidence: ScheduleEvidenceKind;
  priority: Priority;
  sourceIds: string[];
}

export interface MonthlyHealthCheck {
  id: "doctoral-monthly-health-baseline";
  title: string;
  checks: string[];
  relationshipRule: string;
  escalationSignal: string;
  escalationAction: string;
  sourceIds: string[];
}

export interface BufferRule {
  id: string;
  after: string;
  minimum: string;
  rule: string;
}

export interface ConflictRule {
  id: string;
  combination: string[];
  response: string;
}

export interface ScheduleWarningRule {
  id: string;
  condition: string;
  message: string;
  reduction: string;
  priority: Priority;
}

